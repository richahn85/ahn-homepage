"""Apply the Korean V3 header menu and footer links to every page that uses the shared V2 header.

Edits pages in place (they are no longer regenerated by build.py). Run: python scripts/nav_v3.py
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
NAV = [('강의·특강', '/executive-education'), ('기업 자문', '/advisory'), ('AI 전환', '/ax-transformation'),
       ('공공·연구', '/research'), ('실적', '/cases'), ('인사이트', '/insights'), ('소개', '/about')]
# Section pages that should keep their menu item highlighted.
SECTION = {'/management-insights': '/insights', '/professors-question': '/insights', '/people-first': '/about'}
SKIP = ('content/', 'good-sleep-lab/', 'parrfarm/', 'seminar/', 'safety-disclosure-seminar-20260720/')


def current(path):
    for prefix, target in SECTION.items():
        if path.startswith(prefix):
            return target
    for _, url in NAV:
        if path == url or path.startswith(url + '/'):
            return url
    return None


def nav_html(path):
    cur = current(path)
    items = ''.join(f'<li><a href="{u}"{" aria-current=\"page\"" if u == cur else ""}>{n}</a></li>' for n, u in NAV)
    return f'<ul class="nav-links">{items}</ul>'


changed = []
for f in sorted(ROOT.rglob('*.html')):
    rel = f.relative_to(ROOT).as_posix()
    if rel.startswith(SKIP):
        continue
    s = f.open(encoding='utf-8', newline='').read()
    if '<ul class="nav-links">' not in s:
        continue
    path = '/' + rel.removesuffix('index.html').rstrip('/')
    path = '/' if path == '/' else path
    t = re.sub(r'<ul class="nav-links">.*?</ul>', lambda m: nav_html(path), s, count=1, flags=re.S)
    t = t.replace('<a class="nav-cta" href="/contact">자문·협력 문의 <span aria-hidden="true">↗</span></a>',
                  '<a class="nav-cta" href="/contact">문의하기 <span aria-hidden="true">↗</span></a>')
    t = t.replace('<a href="/about">About</a> · <a href="/insights">Insights</a> · <a href="/contact">Contact</a> · <a href="/join/">회원가입</a>',
                  '<a href="/executive-education">강의·특강</a> · <a href="/advisory">기업 자문</a> · <a href="/research">공공·연구</a> · <a href="/cases">실적</a><br><a href="/about">소개</a> · <a href="/people-first">People First</a> · <a href="/contact">문의하기</a> · <a href="/join/">회원가입</a>')
    if t != s:
        f.write_text(t, encoding='utf-8', newline='')
        changed.append(rel)
print(len(changed), 'pages updated')
print('\n'.join(changed))
